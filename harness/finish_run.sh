#!/bin/sh
# Operator-side guard around a run's generated finish.sh (not part of the frozen harness, preregistration §9).
#
#   sudo sh harness/finish_run.sh <run_id>
#
# Refuses unless the run is installed (/home/wspagent/runs/<run_id> exists) and no claude process of wspagent is
# running, then runs runs/wsp/<run_id>/finish.sh unchanged. Added after run d7bb5e22ef57e139, where finish.sh was
# run before install.sh. Paths match configs/harness.yaml (agent_user, agent_runs, main_user).
# Also records launch=interactive in meta.json unless batch.sh recorded launch=batch (harness/set_launch.py), and
# labels finish.sh's directory listings afterwards.
set -u
AGENT_USER=wspagent
AGENT_RUNS=/home/wspagent/runs
MAIN_USER=mainuser
REPO=$(cd "$(dirname "$0")/.." && pwd)

[ $# -eq 1 ] || { echo "usage: sudo sh $0 <run_id>"; exit 2; }
rid=$1
case "$rid" in
  *[!0-9a-f]* | "") echo "finish_run: bad run id '$rid' (expected lowercase hex)"; exit 2 ;;
esac
run="$REPO/runs/wsp/$rid"

[ -f "$run/finish.sh" ] || { echo "finish_run: no $run/finish.sh (unknown run?)"; exit 1; }
[ -e "$run/abandoned.json" ] && { echo "finish_run: run $rid was abandoned; nothing to finish"; exit 1; }
[ -d "$run/archive/rundir" ] && { echo "finish_run: run $rid is already archived"; exit 1; }
[ -d "$AGENT_RUNS/$rid" ] || {
  echo "finish_run: run $rid is not installed ($AGENT_RUNS/$rid missing); nothing to archive."
  echo "  Not installed yet: sudo sh $run/install.sh"
  echo "  Never started and should be dropped: pixi run python harness/make_run.py --abandon $rid --reason \"...\""
  exit 1
}
if pgrep -u "$AGENT_USER" -f '(^|/)claude( |$)' >/dev/null; then
  echo "finish_run: a claude process of $AGENT_USER is still running; exit the session first"; exit 1
fi
[ "$(id -u)" = 0 ] || { echo "finish_run: checks passed; run as root: sudo sh $0 $rid"; exit 2; }

# launch method in meta.json: harness/batch.sh records "batch" when it makes the run; anything else was interactive
runuser -u "$MAIN_USER" -- python3 -I "$REPO/harness/set_launch.py" --run "$rid" --method interactive \
  --by finish_run.sh --if-missing || echo "finish_run: WARNING: could not record the launch method"

# finish.sh (generated by make_run.py, frozen) prints `ls -A /home/wspagent/runs /home/wspagent/.claude/projects`
# (two headers, both empty) and then `ls -A /home/wspagent/.claude` without a header, so the ~/.claude listing
# appears under the "/home/wspagent/runs:" header. The labelled check after it says what each listing is.
sh "$run/finish.sh"
rc=$?
echo "finish_run: labelled check (finish.sh exit $rc):"
for d in "$AGENT_RUNS" "/home/$AGENT_USER/.claude/projects"; do
  n=$(ls -A "$d" 2>/dev/null | wc -l)
  [ "$n" -eq 0 ] && echo "  $d: empty" || echo "WARNING: $d: $n entries"
done
echo "  /home/$AGENT_USER/.claude: $(ls -A "/home/$AGENT_USER/.claude" | wc -l) entries (the unlabelled listing printed by finish.sh above)"
exit $rc
